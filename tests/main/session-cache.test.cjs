const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const ts = require('typescript')
const source = fs.readFileSync(path.join(__dirname, '../../src/main/session-cache.ts'), 'utf8')
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText
const mod = { exports: {} }
new Function('module', 'exports', 'require', compiled)(mod, mod.exports, require)

test('session caches separate dev/build, preserve data and fall back on an inaccessible path', (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'bridgeclip-cache-test-'))
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  const data = path.join(root, 'data')
  fs.mkdirSync(data)
  fs.writeFileSync(path.join(data, 'settings.json'), 'preserved')
  fs.mkdirSync(path.join(data, 'Local Storage'))
  fs.writeFileSync(path.join(data, 'Local Storage', 'preferences'), 'sidebar-profile')
  const dev = mod.exports.prepareSessionCache(data, root, false)
  const prod = mod.exports.prepareSessionCache(data, root, true)
  assert.notEqual(dev.directory, prod.directory)
  assert.equal(dev.fallback, false)
  assert.deepEqual(fs.readdirSync(dev.directory), ['Local Storage'])
  assert.equal(fs.readFileSync(path.join(dev.directory, 'Local Storage', 'preferences'), 'utf8'), 'sidebar-profile')
  fs.writeFileSync(path.join(dev.directory, 'Local Storage', 'preferences'), 'updated')
  mod.exports.prepareSessionCache(data, root, false)
  assert.equal(fs.readFileSync(path.join(dev.directory, 'Local Storage', 'preferences'), 'utf8'), 'updated')
  assert.equal(fs.readFileSync(path.join(data, 'settings.json'), 'utf8'), 'preserved')
  const fallback = mod.exports.prepareSessionCache(path.join(data, 'settings.json'), root, false)
  assert.equal(fallback.fallback, true)
  fs.writeFileSync(path.join(fallback.directory, 'writable'), '')
})
